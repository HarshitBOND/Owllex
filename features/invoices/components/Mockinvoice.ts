export const calculateStats = (invoices: Invoice[]): InvoiceStats => {
  const paid = invoices.filter(inv => inv.status === 'paid');
  const pending = invoices.filter(inv => inv.status === 'pending');
  const overdue = invoices.filter(inv => inv.status === 'overdue');
  const draft = invoices.filter(inv => inv.status === 'draft');
  
  const totalRevenue = paid.reduce((sum, inv) => sum + inv.paidAmount, 0);
  const totalPending = pending.reduce((sum, inv) => sum + inv.total, 0);
  const totalOverdue = overdue.reduce((sum, inv) => sum + inv.total, 0);
  const totalDraft = draft.reduce((sum, inv) => sum + inv.total, 0);
  
  return {
    totalRevenue,
    totalPending,
    totalOverdue,
    totalDraft,
    invoiceCount: invoices.length,
    paidCount: paid.length,
    pendingCount: pending.length,
    overdueCount: overdue.length,
    avgPaymentTime: 12, // mock average
    collectionRate: invoices.length > 0 ? (paid.length / invoices.length) * 100 : 0,
  };
};
